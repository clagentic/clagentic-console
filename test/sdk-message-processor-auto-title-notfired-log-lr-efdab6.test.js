test("lr-efdab6: already_auto_generated reason logged on the steady-state turn after a title has been generated, at debug level not log level", function () {
  var sm = makeSm();
  var processor = makeProcessor(sm, function () {});
  var session = makeSession({ localId: 205, turnCount: 1, titleAutoGenerated: true });

  var logLines = [];
  var debugLines = [];
  var origLog = console.log;
  var origDebug = console.debug;
  console.log = function () { logLines.push(Array.prototype.slice.call(arguments).join(" ")); };
  console.debug = function () { debugLines.push(Array.prototype.slice.call(arguments).join(" ")); };
  try {
    fireResult(processor, session);
  } finally {
    console.log = origLog;
    console.debug = origDebug;
  }

  var gateLogLines = logLines.filter(function (l) { return l.indexOf("[auto-title] gate did not fire:") === 0; });
  var gateDebugLines = debugLines.filter(function (l) { return l.indexOf("[auto-title] gate did not fire:") === 0; });

  assert.equal(gateLogLines.length, 0, "steady-state already_auto_generated must NOT use console.log (would dominate journald at ~1 line/turn for every mature session)");
  assert.equal(gateDebugLines.length, 1, "already_auto_generated must still be recorded, at console.debug, so the negative branch is never silently dropped -- fails against pre-fix code either way (no line at any level)");
  assert.match(gateDebugLines[0], /reason=already_auto_generated/);
  assert.match(gateDebugLines[0], /titleAutoGenerated=true/);
});

