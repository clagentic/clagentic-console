function fireResult(processor, session, cost) {
  processor.processSDKMessage(session, {
    yokeType: "result",
    cost: cost === undefined ? 0.1 : cost,
    duration: 500,
    sessionId: "cli-session-lr-efdab6",
  });
}

// Captures console.log/console.debug calls for the duration of fn(), then
// restores the originals. Returns the array of joined-string lines.
function captureConsole(fn) {
  var lines = [];
  var origLog = console.log;
  var origDebug = console.debug;
  console.log = function () { lines.push(Array.prototype.slice.call(arguments).join(" ")); };
  console.debug = function () { lines.push(Array.prototype.slice.call(arguments).join(" ")); };
  try {
    fn();
  } finally {
    console.log = origLog;
    console.debug = origDebug;
  }
  return lines;
}

function findGateLine(lines) {
  return lines.filter(function (l) { return l.indexOf("[auto-title] gate did not fire:") === 0; });
}

test("lr-efdab6: turn_threshold_not_met reason logged when turnCount has not reached the threshold", function () {
  var sm = makeSm();
  var processor = makeProcessor(sm, function () {});
  var session = makeSession({ localId: 201, turnCount: 0 }); // -> 1 after fireResult, threshold is 2

  var lines = captureConsole(function () { fireResult(processor, session); });
  var gateLines = findGateLine(lines);

  assert.equal(gateLines.length, 1, "exactly one not-fired gate line must be emitted; fails against pre-fix code, which emits none");
  assert.match(gateLines[0], /reason=turn_threshold_not_met/);
  assert.match(gateLines[0], /turnCount=1/);
  assert.match(gateLines[0], /titleAutoGenerated=false/);
  assert.match(gateLines[0], /titleManuallySet=false/);
  assert.match(gateLines[0], /loop=false/);
});

