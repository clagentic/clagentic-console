// session-ai-title.js - gives a session the title its vendor CLI wrote for it.
//
// The console never asks a model for a title. The Claude Code CLI titles each
// session itself and records it in the session's transcript
// (cli-transcript-title.js); this module copies the latest such title onto the
// console session, which is the one place every surface (the picker, prompt
// cards, banners and push, the restart interrupt list, CLI listings) reads a
// title from.
//
// Precedence: a title the operator set by rename always wins; otherwise the
// CLI's title replaces whatever the first-line fallback put there; a session
// whose transcript holds no title keeps the first-line title.

var path = require("path");
var transcriptTitle = require("./cli-transcript-title");

// Vendors whose sessions have a Claude Code transcript. Another vendor's
// thread id names no transcript here, so it is never looked up.
function hasCliTranscript(session) {
  return !session.vendor || session.vendor === "claude";
}

// deps: {
//   sm                         session manager (saveSessionFile, broadcastSessionList)
//   cwd                        the project directory
//   resolveHome(session)       the session owner's home, or null for the daemon's own
//   daemonHome                 the daemon user's home
//   claudeDir?                 overrides the transcript root (tests)
// }
// Returns refresh(session): Promise<boolean>, true when the title changed.
function createAiTitleRefresher(deps) {
  var sm = deps.sm;

  function claudeDirFor(session) {
    if (deps.claudeDir) return deps.claudeDir;
    var ownerHome = deps.resolveHome ? deps.resolveHome(session) : null;
    if (ownerHome) return path.join(ownerHome, ".claude");
    return process.env.CLAUDE_CONFIG_DIR || path.join(deps.daemonHome, ".claude");
  }

  return function refresh(session) {
    if (!session || !session.cliSessionId || session.titleManuallySet) return Promise.resolve(false);
    if (!hasCliTranscript(session)) return Promise.resolve(false);
    var sessionId = session.cliSessionId;
    return transcriptTitle.findTranscript(claudeDirFor(session), [session.cwd, deps.cwd], sessionId)
      .then(function (file) { return file ? transcriptTitle.readLatestAiTitle(file, sessionId) : null; })
      .then(function (title) {
        // Re-checked after the read: a rename can land while the file is read.
        if (!title || session.titleManuallySet || session.title === title) return false;
        session.title = title;
        session.titleAutoGenerated = true;
        session.titleProvisional = false;
        sm.saveSessionFile(session);
        sm.broadcastSessionList();
        return true;
      })
      .catch(function (e) {
        console.error("[ai-title] could not read the session title:", e && e.message ? e.message : e);
        return false;
      });
  };
}

module.exports = { createAiTitleRefresher: createAiTitleRefresher };
